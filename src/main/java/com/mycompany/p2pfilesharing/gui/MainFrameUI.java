    /** Chạy thử giao diện với dữ liệu giả (để demo khi chưa có phần mạng). */
    public void startDemo() {
        if (demoTimer != null) {
            return;
        }
        int[] p = {68, 32};
        demoTimer = new javax.swing.Timer(700, e -> {
            p[0] = Math.min(100, p[0] + 4);
            p[1] = Math.min(100, p[1] + 6);
            showTransfer(1, "project_p2p.zip", true, p[0], String.format("%.1f MB / 7.1 MB", 7.1 * p[0] / 100));
            showTransfer(2, "IMG_0187.jpg", false, p[1], String.format("%.1f MB / 3.7 MB", 3.7 * p[1] / 100));
            if (p[0] == 100 && p[1] == 100) {
                addLog("File tải xuống hoàn tất!");
                demoTimer.stop();
                demoTimer = null;
            }
        });
        demoTimer.start();
    }

