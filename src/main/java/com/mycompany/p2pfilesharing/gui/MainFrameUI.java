    private static void thinScrollBar(JScrollPane sp) {
        sp.getVerticalScrollBar().setPreferredSize(new java.awt.Dimension(8, 0));
        sp.getVerticalScrollBar().setOpaque(false);
        sp.getVerticalScrollBar().setUI(new BasicScrollBarUI() {
            @Override
            protected void paintThumb(Graphics g, JComponent c, java.awt.Rectangle r) {
                Graphics2D g2 = (Graphics2D) g.create();
                g2.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
                g2.setColor(new Color(0xC9, 0xCD, 0xE8));
                g2.fillRoundRect(r.x + 1, r.y, r.width - 2, r.height, 8, 8);
                g2.dispose();
            }

            @Override
            protected void paintTrack(Graphics g, JComponent c, java.awt.Rectangle r) {
            }

            @Override
            protected javax.swing.JButton createDecreaseButton(int o) {
                return zero();
            }

            @Override
            protected javax.swing.JButton createIncreaseButton(int o) {
                return zero();
            }

            private javax.swing.JButton zero() {
                javax.swing.JButton b = new javax.swing.JButton();
                b.setPreferredSize(new java.awt.Dimension(0, 0));
                return b;
            }
        });
    }

    private static void styleProgress(JProgressBar bar) {
        bar.setUI(new BasicProgressBarUI() {
            @Override
            public void paint(Graphics g, JComponent c) {
                Graphics2D g2 = (Graphics2D) g.create();
                g2.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
                int h = 6, y = (c.getHeight() - h) / 2, w = c.getWidth();
                g2.setColor(c.getBackground());
                g2.fillRoundRect(0, y, w, h, h, h);
                g2.setColor(c.getForeground());
                g2.fillRoundRect(0, y, (int) (w * bar.getPercentComplete()), h, h, h);
                g2.dispose();
            }
        });
    }

    private void showSuccessToast(String message) {
        JWindow toast = new JWindow(this);
        JLabel lbl = new JLabel(message, SwingConstants.CENTER);
        lbl.setFont(new Font("Segoe UI", Font.BOLD, 13));
        lbl.setForeground(Color.WHITE);
        lbl.setOpaque(true);
        lbl.setBackground(new Color(35, 160, 100));
        lbl.setBorder(BorderFactory.createEmptyBorder(12, 24, 12, 24));
        toast.add(lbl);
        toast.pack();
        toast.setLocation(getX() + getWidth() - toast.getWidth() - 30,
                          getY() + getHeight() - toast.getHeight() - 60);
        toast.setVisible(true);
        Timer t = new Timer(2000, e -> toast.dispose());
        t.setRepeats(false);
        t.start();
    }
