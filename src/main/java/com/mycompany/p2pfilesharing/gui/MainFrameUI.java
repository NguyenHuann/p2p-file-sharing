private static String formatSize(long b) {
    if (b < 1024) return b + " B";
    double kb = b / 1024.0;
    if (kb < 1024) return String.format("%.1f KB", kb);
    double mb = kb / 1024;
    if (mb < 1024) return String.format("%.1f MB", mb);
    return String.format("%.2f GB", mb / 1024);
}

