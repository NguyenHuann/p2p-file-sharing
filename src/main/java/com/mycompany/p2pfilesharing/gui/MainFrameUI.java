private void sharePending() {
    if (pendingFiles.isEmpty()) {
        addLog("Chưa chọn file nào - hãy bấm \"Chọn file / thư mục\"");
        return;
    }
    String name = (String) cboSharePeer.getSelectedItem();
    if (name == null) {
        addLog("Chưa có máy nào online để gửi");
        return;
    }
    DefaultTableModel m = (DefaultTableModel) tblPeers.getModel();
    for (int i = 0; i < m.getRowCount(); i++) {
        if (name.equals(String.valueOf(m.getValueAt(i, 0)))) {
            int port = 0;
            try {
                port = Integer.parseInt(String.valueOf(m.getValueAt(i, 2)).trim());
            } catch (NumberFormatException ignore) {
            }
            addLog("Yêu cầu gửi " + pendingFiles.size() + " mục tới " + name);
            listener.onSendRequested(new ArrayList<>(pendingFiles), name,
                    String.valueOf(m.getValueAt(i, 1)), port);
            return;
        }
    }
}

