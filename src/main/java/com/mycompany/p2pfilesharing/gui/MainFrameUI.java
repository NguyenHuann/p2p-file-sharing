    /** Thêm 1 dòng vào khung trạng thái (JTextArea txtLog), tự cuộn xuống cuối. */
    public void addLog(String message) {
        ui(() -> {
            String time = LocalTime.now().format(DateTimeFormatter.ofPattern("HH:mm:ss"));
            txtLog.append("●  " + time + "    " + message + "\n");
            txtLog.setCaretPosition(txtLog.getDocument().getLength());
        });
    }

    /** Thêm máy mới, hoặc cập nhật nếu đã có (so theo tên máy). lastActive vd "00:00:12". */
    public void addOrUpdatePeer(String name, String ip, int port, String lastActive) {
        ui(() -> {
            DefaultTableModel m = (DefaultTableModel) tblPeers.getModel();
            Object[] row = {name, ip, String.valueOf(port), "Online", lastActive};
            for (int i = 0; i < m.getRowCount(); i++) {
                if (name.equals(m.getValueAt(i, 0))) {
                    for (int c = 0; c < row.length; c++) {
                        m.setValueAt(row[c], i, c);
                    }
                    return;
                }
            }
            m.addRow(row);
            refreshPeerCount();
        });
    }

    /** Xóa 1 máy (khi máy đó offline). */
    public void removePeer(String name) {
        ui(() -> {
            DefaultTableModel m = (DefaultTableModel) tblPeers.getModel();
            for (int i = m.getRowCount() - 1; i >= 0; i--) {
                if (name.equals(m.getValueAt(i, 0))) {
                    m.removeRow(i);
                }
            }
            refreshPeerCount();
        });
    }

    /** Xóa hết danh sách máy. */
    public void clearPeers() {
        ui(() -> {
            ((DefaultTableModel) tblPeers.getModel()).setRowCount(0);
            refreshPeerCount();
        });
    }

    /**
     * Cập nhật ô truyền tải.
     * @param slot 1 hoặc 2
     * @param sending true = đang gửi, false = đang nhận
     * @param percent 0..100
     * @param sizeText vd "4.8 MB / 7.1 MB  ·  00:00:12"
     */
    public void showTransfer(int slot, String fileName, boolean sending, int percent, String sizeText) {
        ui(() -> {
            JProgressBar bar = (slot == 1) ? prgTransfer1 : prgTransfer2;
            javax.swing.JLabel name = (slot == 1) ? lblTransfer1Name : lblTransfer2Name;
            javax.swing.JLabel state = (slot == 1) ? lblTransfer1State : lblTransfer2State;
            javax.swing.JLabel size = (slot == 1) ? lblTransfer1Size : lblTransfer2Size;
            name.setText(fileName);
            state.setText((sending ? "Đang gửi... (" : "Đang nhận... (") + percent + "%)");
            bar.setValue(percent);
            size.setText(sizeText);
        });
    }

    /** Đưa ô truyền tải về trạng thái rảnh. */
    public void clearTransfer(int slot) {
        showTransfer(slot, "(trống)", true, 0, "");
        ui(() -> ((slot == 1) ? lblTransfer1State : lblTransfer2State).setText("Chưa có truyền tải"));
    }

