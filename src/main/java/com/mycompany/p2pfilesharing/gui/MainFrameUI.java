    private void btnMenuShareActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMenuShareActionPerformed
        if (pendingFiles.isEmpty()) {
            addLog("Chưa chọn file nào - hãy bấm \"Chọn file / thư mục\" hoặc kéo thả vào ô bên dưới");
            return;
        }
        int row = tblPeers.getSelectedRow();
        if (row < 0) {
            addLog("Hãy chọn 1 máy trong bảng \"Danh sách Peer Online\" để gửi");
            return;
        }
        row = tblPeers.convertRowIndexToModel(row);
        DefaultTableModel m = (DefaultTableModel) tblPeers.getModel();
        String name = String.valueOf(m.getValueAt(row, 0));
        String ip = String.valueOf(m.getValueAt(row, 1));
        int port = 0;
        try {
            port = Integer.parseInt(String.valueOf(m.getValueAt(row, 2)).trim());
        } catch (NumberFormatException ignore) {
        }
        addLog("Yêu cầu gửi " + pendingFiles.size() + " mục tới " + name);
        listener.onSendRequested(new ArrayList<>(pendingFiles), name, ip, port);
    }//GEN-LAST:event_btnMenuShareActionPerformed

