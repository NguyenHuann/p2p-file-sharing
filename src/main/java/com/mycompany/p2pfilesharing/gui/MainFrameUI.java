    /** Tính tổng dung lượng file / thư mục. */
    private static long sizeOf(File f) {
        if (f.isFile()) {
            return f.length();
        }
        long total = 0;
        File[] children = f.listFiles();
        if (children != null) {
            for (File c : children) {
                total += sizeOf(c);
            }
        }
        return total;
    }

    /** Hiện file vừa chọn vào ô "Truyền tải hiện tại" và chạy tiến trình mô phỏng. */
    private void startLocalTransfer(File f) {
        final int slot = !slotBusy[1] ? 1 : (!slotBusy[2] ? 2 : 0);
        if (slot == 0) {
            addLog("Đã có 2 truyền tải đang chạy, chưa thể hiện thêm: " + f.getName());
            return;
        }
        slotBusy[slot] = true;
        statSending++;
        updateStats();
        final String name = f.getName();
        final long total = sizeOf(f);

        // Đặt ô về trống trước để reset trạng thái cũ (kể cả khi trùng tên file)
        showTransfer(slot, "(trống)", true, 0, "", "—");
        showTransfer(slot, name, true, 0, formatSize(0) + " / " + formatSize(total), "—");

        double seconds = Math.max(3, Math.min(15, total / (5.0 * 1024 * 1024)));
        final int steps = (int) (seconds * 10);
        final int[] tick = {0};
        final Timer[] t = new Timer[1];

        t[0] = new Timer(100, e -> {
            if (slot == 1 && transfer1Paused) {
                return;                                  // đang tạm dừng thì đứng yên
            }
                        if (slot == 2 && transfer2Stopped) {         // đã bấm dừng thì hủy
                t[0].stop();
                slotBusy[slot] = false;
                statSending--;
                updateStats();
                return;
            }
            tick[0]++;
            int pct = Math.min(100, tick[0] * 100 / steps);
            long done = total * pct / 100;
            showTransfer(slot, name, true, pct,
                    formatSize(done) + " / " + formatSize(total)
                    + "  ·  " + String.format("00:00:%02d", tick[0] / 10), "—");
             if (pct >= 100) {
                t[0].stop();
                statSending--;
                statFilesDone++;
                updateStats();
                // giữ ô thêm 2,2s để hiệu ứng tự xóa ô (1,8s) không xóa nhầm ô của file mới
                Timer rel = new Timer(2200, ev -> slotBusy[slot] = false);
                rel.setRepeats(false);
                rel.start();
            }
        });
        t[0].start();
    }
        private final java.util.Set<String> downloading = new java.util.HashSet<>();

    /** Đổi chữ "7.1 MB" thành số byte. */
    private static long parseSize(String s) {
        try {
            String[] p = s.trim().split("\\s+");
            double v = Double.parseDouble(p[0].replace(",", "."));
            String u = p.length > 1 ? p[1].toUpperCase() : "B";
            switch (u) {
                case "KB": return (long) (v * 1024);
                case "MB": return (long) (v * 1024 * 1024);
                case "GB": return (long) (v * 1024 * 1024 * 1024);
                default: return (long) v;
            }
        } catch (Exception e) {
            return 0;
        }
    }

    /** Mô phỏng tải 1 file từ máy khác: hiện ở ô Truyền tải hiện tại (chiều NHẬN). */
    private void startLocalDownload(String fileName, String sizeText, String peerName) {
        if (downloading.contains(fileName)) {
            addLog("File " + fileName + " đang được tải rồi");
            return;
        }
        final int slot = !slotBusy[1] ? 1 : (!slotBusy[2] ? 2 : 0);
        if (slot == 0) {
            addLog("Đã có 2 truyền tải đang chạy, hãy đợi rồi tải " + fileName);
            return;
        }
        slotBusy[slot] = true;
        downloading.add(fileName);
        statReceiving++;
        updateStats();

        final long total = parseSize(sizeText);
        showTransfer(slot, "(trống)", false, 0, "", "—");
        showTransfer(slot, fileName, false, 0, formatSize(0) + " / " + formatSize(total), peerName);

        double seconds = Math.max(3, Math.min(15, total / (5.0 * 1024 * 1024)));
        final int steps = (int) (seconds * 10);
        final int[] tick = {0};
        final Timer[] t = new Timer[1];

        t[0] = new Timer(100, e -> {
            if (slot == 1 && transfer1Paused) {
                return;
            }
            if (slot == 2 && transfer2Stopped) {
                t[0].stop();
                slotBusy[slot] = false;
                downloading.remove(fileName);
                statReceiving--;
                updateStats();
                addTransferRecord(fileName, "Nhận", peerName, "Đã dừng");
                return;
            }
            tick[0]++;
            int pct = Math.min(100, tick[0] * 100 / steps);
            long done = total * pct / 100;
            showTransfer(slot, fileName, false, pct,
                    formatSize(done) + " / " + formatSize(total)
                    + "  ·  " + String.format("00:00:%02d", tick[0] / 10), peerName);
            if (pct >= 100) {
                t[0].stop();
                downloading.remove(fileName);
                statReceiving--;
                statFilesDone++;
                updateStats();
                Timer rel = new Timer(2200, ev -> slotBusy[slot] = false);
                rel.setRepeats(false);
                rel.start();
            }
        });
        t[0].start();
    }
